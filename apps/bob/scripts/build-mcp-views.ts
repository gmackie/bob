// Bundles the MCP Apps views (src/server/mcp/views/*.client.ts) into
// src/server/mcp/views/generated.ts. The Worker can't bundle at runtime, so the
// output is committed; `--check` (run by views.test.ts) fails when it is stale.
//
//   pnpm -F @bob/blder exec tsx scripts/build-mcp-views.ts [--check]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

import { VIEWS, viewDocument, type ViewName } from "../src/server/mcp/views/html";

const app = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const views = join(app, "src/server/mcp/views");
const target = join(views, "generated.ts");

export async function generate(): Promise<string> {
  const entries: string[] = [];
  for (const name of Object.keys(VIEWS) as ViewName[]) {
    const result = await build({
      entryPoints: [join(views, VIEWS[name].entry)],
      bundle: true,
      write: false,
      format: "esm",
      platform: "browser",
      target: "es2022",
      minify: true,
      legalComments: "none",
      // Resolves `~/` through the app's tsconfig paths.
      tsconfig: join(app, "tsconfig.json"),
    });
    entries.push(`  ${name}: ${JSON.stringify(viewDocument(name, result.outputFiles[0]!.text))},`);
  }
  return `// Generated by scripts/build-mcp-views.ts. Do not edit.\nexport const VIEW_HTML = {\n${entries.join("\n")}\n} as const;\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = await generate();
  if (process.argv.includes("--check")) {
    if (readFileSync(target, "utf8") !== output) {
      console.error("src/server/mcp/views/generated.ts is stale: run scripts/build-mcp-views.ts");
      process.exit(1);
    }
  } else writeFileSync(target, output);
}
